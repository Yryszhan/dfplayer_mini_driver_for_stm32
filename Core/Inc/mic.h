/**
 * mic.h - детектор звука на MAX9814 для STM32F1, чистый CMSIS.
 *
 * MAX9814 выдаёт аналог с DC-смещением 1.25 В и размахом до 2 Vpp.
 * Меряем размах (peak-to-peak) за окно и сравниваем с порогом.
 *
 * Подключение:
 *   MAX9814 VDD  -> 3.3V  (не 5V, чтобы не выйти за диапазон АЦП)
 *   MAX9814 GND  -> GND
 *   MAX9814 OUT  -> PA0
 *   MAX9814 GAIN -> VDD = 40 дБ, GND = 50 дБ, не подключен = 60 дБ
 *   MAX9814 AR   -> не подключать (по умолчанию 1:4000)
 *
 * Для детектора шума ставь GAIN на VDD (40 дБ) - меньше ложных срабатываний.
 */
#ifndef MIC_H
#define MIC_H

#include "stm32f1xx.h"
#include <stdint.h>

/* Инициализация ADC1 на указанном канале.
   channel: 0 для PA0, 1 для PA1 и т.д. (0..7 на порту A) */
void MIC_Init(uint8_t channel);

/* Размах сигнала за окно измерения, в единицах АЦП (0..4095).
   Блокирует примерно на samples/1мс. */
uint16_t MIC_ReadLevel(void);

/* Уровень тишины, измеренный при старте. */
uint16_t MIC_GetBaseline(void);

/* Перезамерить уровень тишины. Вызывать в тихой обстановке. */
void MIC_Calibrate(void);

/* Псевдослучайное число 1..max. Зерно берётся из шума АЦП. */
uint16_t MIC_Random(uint16_t max);

#endif /* MIC_H */